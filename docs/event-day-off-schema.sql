-- Event Day Off credits — run this once in the Supabase SQL Editor
-- (project hbxzbowkucpqlhxdomap) before using the new "Grant Event Day
-- Off" button on the admin Time Off tab.
--
-- A separate table from time_off_records on purpose: this isn't a
-- clock-out/clock-in trip, it's a full day off that HR grants to staff
-- who won a company event. It never deducts Annual Leave and is never
-- counted towards the existing 4-hour monthly Time Off cap (that cap is
-- computed solely from time_off_records, which this table never touches).
--
-- Admin grants a credit with no date attached; the staff member later
-- picks their own date to redeem it -- redeemed_date/redeemed_at stay
-- null until then. expires_at is optional; leave it blank for a credit
-- that never expires.

create table event_day_off_credits (
  id bigint generated by default as identity primary key,
  staff_name text not null,
  staff_email text not null,
  reason text not null,               -- the event, e.g. "Family Day 2026 — Tug of War Champions"
  granted_by text,
  granted_by_email text,
  expires_at date,
  redeemed_date date,
  redeemed_at timestamptz,
  created_at timestamptz not null default now()
);

alter table event_day_off_credits enable row level security;

-- Matches the app-wide convention (see docs/time-off-schema.sql and every
-- other table): read and written directly from the client via the
-- hardcoded anon key, with only UI-level ownership checks, not
-- database-level ones.
create policy "anon full access" on event_day_off_credits
  for all to anon using (true) with check (true);
