-- Faulty Complain "In Progress" step — run this once in the Supabase SQL
-- Editor (project hbxzbowkucpqlhxdomap) before using the "I'll handle this"
-- and "+ Add update" buttons (js/faulty-progress.js).
--
-- Safe to run more than once.

-- 1. Who is handling a complaint, and since when. Status can now also be
--    'in_progress' (between 'open' and 'resolved').
alter table faulty_complaints add column if not exists handled_by text;
alter table faulty_complaints add column if not exists handled_by_email text;
alter table faulty_complaints add column if not exists handled_at timestamptz;

-- Only matters if the table was created with a check on status that lists
-- just 'open' and 'resolved' -- this removes that check if it exists, and
-- does nothing otherwise.
alter table faulty_complaints drop constraint if exists faulty_complaints_status_check;

-- 2. The update history: one row per note.
--    kind: 'claim'   -- the note written when tapping "I'll handle this"
--          'update'  -- "+ Add update"
--          'resolve' -- the optional note written when marking it resolved
create table if not exists faulty_complaint_updates (
  id bigint generated by default as identity primary key,
  complaint_id bigint not null references faulty_complaints(id) on delete cascade,
  kind text not null default 'update',
  note text not null,
  author_name text,
  author_email text,
  created_at timestamptz not null default now()
);

create index if not exists faulty_complaint_updates_complaint_idx
  on faulty_complaint_updates (complaint_id, created_at);

alter table faulty_complaint_updates enable row level security;

-- Matches the app-wide convention (see docs/time-off-schema.sql and every
-- other table): read and written directly from the client via the
-- hardcoded anon key, with only UI-level checks.
drop policy if exists "anon full access" on faulty_complaint_updates;
create policy "anon full access" on faulty_complaint_updates
  for all to anon using (true) with check (true);
