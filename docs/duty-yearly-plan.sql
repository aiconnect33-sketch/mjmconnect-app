-- Duty Roster yearly plan — run this once in the Supabase SQL Editor
-- (project hbxzbowkucpqlhxdomap) before using the "Yearly plan" button on
-- the Duty Roster (js/duty-plan.js).
--
-- Each duty role can have a yearly plan: who's on duty in each month
-- (Jan..Dec), the same every year. The app keeps duty_roster filled in
-- for this month + the next 2 from that plan, by calling
-- ensure_duty_plan() below -- so everything that already reads
-- duty_roster (the Duty Roster screen, faulty-report emails and push
-- notifications) keeps working unchanged.
--
-- Safe to run more than once.

-- 1. The plan: one row per person per month per duty role.
create table if not exists duty_yearly_plan (
  id bigint generated by default as identity primary key,
  duty_role text not null,
  month int not null check (month between 1 and 12),
  staff_name text not null,
  staff_email text,
  created_at timestamptz not null default now()
);

alter table duty_yearly_plan enable row level security;
-- Same app-wide convention as every other table (see docs/time-off-schema.sql).
drop policy if exists "anon full access" on duty_yearly_plan;
create policy "anon full access" on duty_yearly_plan
  for all to anon using (true) with check (true);

-- 2. Which months have already been filled in from the plan, per role.
--    A month is only ever filled in once: if someone later deletes or
--    changes it by hand, it stays that way instead of coming back.
create table if not exists duty_plan_generated (
  duty_role text not null,
  month_start date not null,
  created_at timestamptz not null default now(),
  primary key (duty_role, month_start)
);

alter table duty_plan_generated enable row level security;
drop policy if exists "anon full access" on duty_plan_generated;
create policy "anon full access" on duty_plan_generated
  for all to anon using (true) with check (true);

-- 3. Marks roster rows that came from the plan:
--      null      -- added by hand (as before)
--      'plan'    -- filled in from the yearly plan
--      'changed' -- filled in from the plan, then changed for that month only
alter table duty_roster add column if not exists plan_status text;

-- 4. Fills in this month + the next (months_ahead - 1) months from the plan.
--    For each role and month: skipped if it was already filled in before,
--    or if someone already added that month by hand (theirs is kept).
--    Uses Malaysia time for "this month". The advisory lock stops two
--    phones opening the app at the same moment from filling a month twice.
create or replace function ensure_duty_plan(months_ahead int default 3)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  m date;
  m_end date;
  r record;
  this_month date := date_trunc('month', (now() at time zone 'Asia/Kuala_Lumpur'))::date;
begin
  perform pg_advisory_xact_lock(4207011);
  for i in 0 .. greatest(months_ahead, 1) - 1 loop
    m := (this_month + make_interval(months => i))::date;
    m_end := (m + interval '1 month' - interval '1 day')::date;
    for r in
      select distinct duty_role from duty_yearly_plan
      where month = extract(month from m)::int
    loop
      continue when exists (
        select 1 from duty_plan_generated g where g.duty_role = r.duty_role and g.month_start = m
      );
      if not exists (
        select 1 from duty_roster d
        where d.duty_role = r.duty_role and d.date_from <= m_end and d.date_to >= m
      ) then
        insert into duty_roster (duty_role, staff_name, staff_email, date_from, date_to, period, plan_status)
        select p.duty_role, p.staff_name, p.staff_email, m, m_end, m::text || ' to ' || m_end::text, 'plan'
        from duty_yearly_plan p
        where p.duty_role = r.duty_role and p.month = extract(month from m)::int;
      end if;
      insert into duty_plan_generated (duty_role, month_start) values (r.duty_role, m)
      on conflict do nothing;
    end loop;
  end loop;
end;
$$;

grant execute on function ensure_duty_plan(int) to anon;

