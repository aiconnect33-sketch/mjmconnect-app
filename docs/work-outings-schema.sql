-- Out for Work (Time Off tab → 💼 Work) — run this once in the Supabase SQL
-- Editor (project hbxzbowkucpqlhxdomap) before using the Work side of the
-- Time Off tab and the 💼 Work tab of the admin Time Off Report.
--
-- Work outings live in their OWN table on purpose, never in
-- time_off_records: nothing that counts personal Time Off (the 4h/month
-- meter, the 2h/trip limit, cancellation approvals, the Annual Leave
-- reminders, the Google Sheet sync) ever reads this table, so a work errand
-- can't be charged to anyone's allowance by mistake.
--
-- No approval step: a work outing is simply visible to every staff member
-- (Home "Currently Out", the live "Out for work right now" list and All Work
-- Outings) and to admins in the Time Off Report.
--
-- Until this has been run, the Work side shows a "not set up yet" message
-- and personal Time Off keeps working exactly as before.

create table if not exists work_outings (
  id bigint generated by default as identity primary key,
  staff_name text not null,
  staff_email text not null,
  purpose text not null,                -- "What for", e.g. "Submit documents to LHDN"
  time_out timestamptz not null,
  time_in timestamptz,                  -- null while still out
  duration_minutes integer,             -- real clock minutes, set at Time In; never charged
  entry_type text not null default 'live'
    check (entry_type in ('live','edited','voided')),
  original_time_in timestamptz,         -- set once, on an admin's first correction
  corrected_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists work_outings_time_out_idx on work_outings (time_out desc);
create index if not exists work_outings_open_idx on work_outings (staff_email) where time_in is null;

alter table work_outings enable row level security;

-- Same app-wide convention as time_off_records (see docs/time-off-schema.sql):
-- read and written from the client with the anon key, ownership checked in
-- the UI.
drop policy if exists "anon full access" on work_outings;
create policy "anon full access" on work_outings
  for all to anon using (true) with check (true);
